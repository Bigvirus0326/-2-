def legacy(b):
    return B.F.variant(b,B.SPECS)


def block_help(b):
    op=b.get("op","")
    selected=legacy(b)
    text=BLOCKS.get(selected) or BLOCKS.get(op)
    if not text:
        if op in B.F.FAMILIES:
            text=B.F.FAMILIES[op][0] + "에 관련된 동작을 목록에서 고릅니다. 선택한 동작에 필요한 입력칸만 표시됩니다."
        elif (B.SPECS.get(op) or {}).get("cat")=="mod_api":
            text="가져온 모드가 제공하는 전용 기능입니다. 해당 원본 모드가 있어야 동작합니다. 일반 효과를 만들 때는 기본 행동 블록을 먼저 사용하세요."
        else:
            caption=B.SPECS.get(op,{}).get("ko",op)
            text=re.sub(r"\{\w+\}","입력한 값",caption) + " 동작을 실행합니다. 입력칸에 마우스를 올리면 각 값의 뜻을 볼 수 있습니다."
    caption=B.SPECS.get(selected,{}).get("ko","")
    terms=[meaning for word,meaning in WORDS.items() if word in caption]
    if terms:
        text += "\n" + "\n".join(terms[:3])
    if op in B.F.FAMILIES:
        choices=" / ".join(label for _,label in B.F.modes(b))
        text += "\n선택할 수 있는 동작: " + choices
    return text


